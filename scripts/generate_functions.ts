// ============================================================
// generate_functions.ts
// Reads packages/core/src/schema.ts and generates:
//   - packages/core/src/functions/{idx,sgx,klse}/*.ts  (per-endpoint facades)
//   - packages/core/src/functions/index.ts              (barrel, re-exports only)
//   - deployments/excel/src/functions/functions.json     (Excel metadata)
//
// Usage: npx tsx scripts/generate_functions.ts
// ============================================================
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(__dirname, "..");
const SCHEMA_PATH = path.resolve(
  PROJECT_ROOT,
  "packages",
  "core",
  "src",
  "schema.ts",
);
const CORE_FUNCTIONS_DIR = path.resolve(
  PROJECT_ROOT,
  "packages",
  "core",
  "src",
  "functions",
);
const DEPLOYMENT_FUNCTIONS_DIR = path.resolve(
  PROJECT_ROOT,
  "deployments",
  "excel",
  "src",
  "functions",
);
const OUTPUT_JSON = path.resolve(DEPLOYMENT_FUNCTIONS_DIR, "functions.json");

// ── Types ─────────────────────────────────────────────────────

interface ParamDef {
  name: string;
  type: string;
  description: string;
  optional?: boolean;
  example?: string;
}

interface EndpointDef {
  functionName: string;
  path: string;
  description: string;
  params: ParamDef[];
  extraQueryParams?: Record<string, unknown>;
}

// ── Helpers ──────────────────────────────────────────────────

/** Strip prefix for Excel function name. */
function excelName(functionName: string): string {
  if (functionName.startsWith("SECTORS_SGX_"))
    return "SGX_" + functionName.slice(12);
  if (functionName.startsWith("SECTORS_KLSE_"))
    return "KLSE_" + functionName.slice(13);
  if (functionName.startsWith("SECTORS_")) return functionName.slice(8);
  return functionName;
}

function exchangeDir(functionName: string): string {
  if (functionName.startsWith("SECTORS_SGX_")) return "sgx";
  if (functionName.startsWith("SECTORS_KLSE_")) return "klse";
  if (functionName.startsWith("SECTORS_")) return "idx";
  throw new Error(`Cannot determine exchange for: ${functionName}`);
}

function fileName(functionName: string): string {
  let stripped = functionName;
  for (const prefix of ["SECTORS_SGX_", "SECTORS_KLSE_", "SECTORS_"]) {
    if (stripped.startsWith(prefix)) {
      stripped = stripped.slice(prefix.length);
      break;
    }
  }
  return stripped
    .toLowerCase()
    .replace(/_/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

function cap(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function excelType(type: string): "string" | "number" | "boolean" {
  if (type === "number") return "number";
  if (type === "boolean") return "boolean";
  return "string";
}

// ── Generate per-file facade ─────────────────────────────────

function writeFacade(
  def: EndpointDef,
  outDir: string,
  outFileBase: string,
): void {
  const fnName = excelName(def.functionName);
  const constName = `${def.functionName}_DEF`;

  const pathParams = def.params.filter((p) => def.path.includes(`{${p.name}}`));
  const queryParams = def.params.filter(
    (p) => !def.path.includes(`{${p.name}}`),
  );
  const allParams = [...pathParams, ...queryParams];

  const funcParams = allParams.map(
    (p) => `${p.name}${p.optional ? "?" : ""}: string`,
  );
  const jsdocParams = allParams.map(
    (p) =>
      ` * @param {string} ${p.name}${p.optional ? " [OPTIONAL]" : ""} - ${cap(p.description.replace(/\.$/, ""))}.`,
  );

  const sig =
    funcParams.length > 0 ? funcParams.map((p) => `  ${p}`).join(",\n") : "";
  const paramSection = sig ? `\n${sig}\n` : "";
  const argsStr = `{ ${def.params.map((p) => p.name).join(", ")} }`;

  const content = [
    "// ============================================================",
    "// AUTO-GENERATED by scripts/generate_functions.ts",
    "// DO NOT EDIT MANUALLY.",
    "// Regenerate with: npx tsx scripts/generate_functions.ts",
    "// ============================================================",
    'import { executeEndpoint } from "../../factory";',
    `import { ${constName} } from "../../schema";`,
    "",
    "/**",
    ` * ${def.description}`,
    ...jsdocParams,
    " * @returns {string[][]}",
    " * @customfunction",
    " */",
    `export async function ${fnName}(${paramSection}) {`,
    `  return executeEndpoint(${constName}, ${argsStr});`,
    "}",
    "",
  ];

  const outPath = path.resolve(outDir, `${outFileBase}.ts`);
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(outPath, content.join("\n"), "utf-8");
}

// ── Generate core functions barrel (re-exports only) ─────────

interface GeneratedInfo {
  functionName: string;
  exchange: string;
  fileBase: string;
}

function writeCoreBarrel(generated: GeneratedInfo[]): void {
  const lines: string[] = [
    "// ============================================================",
    "// functions/index.ts — AUTO-GENERATED by scripts/generate_functions.ts",
    "// DO NOT EDIT MANUALLY.",
    "// Re-exports all facade functions by exchange.",
    "// ============================================================",
    "",
  ];

  const idx = generated
    .filter((g) => g.exchange === "idx")
    .sort((a, b) => a.fileBase.localeCompare(b.fileBase));
  const sgx = generated
    .filter((g) => g.exchange === "sgx")
    .sort((a, b) => a.fileBase.localeCompare(b.fileBase));
  const klse = generated
    .filter((g) => g.exchange === "klse")
    .sort((a, b) => a.fileBase.localeCompare(b.fileBase));

  lines.push("// ── Indonesia (IDX) ────────────────────────────");
  for (const g of idx) lines.push(`export * from "./idx/${g.fileBase}";`);

  lines.push("");
  lines.push("// ── Singapore (SGX) ────────────────────────────");
  for (const g of sgx) lines.push(`export * from "./sgx/${g.fileBase}";`);

  lines.push("");
  lines.push("// ── Malaysia (KLSE) ────────────────────────────");
  for (const g of klse) lines.push(`export * from "./klse/${g.fileBase}";`);
  lines.push("");

  const indexPath = path.resolve(CORE_FUNCTIONS_DIR, "index.ts");
  fs.writeFileSync(indexPath, lines.join("\n"), "utf-8");
  console.log(`  Core barrel:  ${indexPath}`);
}

// ── Generate functions.json ─────────────────────────────────

interface JsonParam {
  name: string;
  description: string;
  type: "string" | "number" | "boolean";
  optional?: true;
}

interface JsonFunction {
  id: string;
  name: string;
  description: string;
  parameters: JsonParam[];
  result: { dimensionality: "matrix"; type: "string" };
}

function generateJson(apiSchema: EndpointDef[]): string {
  const functions: JsonFunction[] = apiSchema.map((def) => {
    const name = excelName(def.functionName);
    const parameters: JsonParam[] = def.params.map((p) => {
      const entry: JsonParam = {
        name: p.name,
        description: p.description,
        type: excelType(p.type),
      };
      if (p.optional) entry.optional = true;
      return entry;
    });

    return {
      id: name,
      name,
      description: def.description,
      parameters,
      result: { dimensionality: "matrix", type: "string" },
    };
  });

  return JSON.stringify(
    { allowCustomDataForDataTypeAny: true, functions },
    null,
    4,
  );
}

// ── Main ─────────────────────────────────────────────────────

async function main() {
  const schemaUrl = pathToFileURL(SCHEMA_PATH).href;
  const { API_SCHEMA } = (await import(schemaUrl)) as {
    API_SCHEMA: EndpointDef[];
  };

  // ── Generate per-file facades ──────────────────────────────
  const generated: GeneratedInfo[] = [];

  for (const def of API_SCHEMA) {
    const exchange = exchangeDir(def.functionName);
    const fileBase = fileName(def.functionName);
    const outDir = path.resolve(CORE_FUNCTIONS_DIR, exchange);

    writeFacade(def, outDir, fileBase);
    generated.push({ functionName: def.functionName, exchange, fileBase });
  }

  console.log(`  Facades: ${generated.length} file(s)`);

  // ── Generate core barrel ──────────────────────────────────
  writeCoreBarrel(generated);

  // ── Generate functions.json ────────────────────────────────
  fs.mkdirSync(DEPLOYMENT_FUNCTIONS_DIR, { recursive: true });
  fs.writeFileSync(OUTPUT_JSON, generateJson(API_SCHEMA), "utf-8");
  console.log(`  JSON:    ${OUTPUT_JSON}`);

  // ── Summary ────────────────────────────────────────────────
  const idxCount = generated.filter((g) => g.exchange === "idx").length;
  const sgxCount = generated.filter((g) => g.exchange === "sgx").length;
  const klseCount = generated.filter((g) => g.exchange === "klse").length;

  console.log(`\n── Summary ──────────────────────────────────`);
  console.log(`  IDX:  ${idxCount}`);
  console.log(`  SGX:  ${sgxCount}`);
  console.log(`  KLSE: ${klseCount}`);
}

main().catch((err) => {
  console.error("Fatal error:", err);
  process.exit(1);
});
