// ============================================================
// generate_schema.ts
// Reads sectors_extensions/packages/core/src/schema.ts and
// generates src/functions/schema.ts with the same endpoint
// definitions, but as standalone plain-JS-compatible TS.
//
// Usage: npx tsx scripts/generate_schema.ts
// ============================================================
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(__dirname, "..");
const INPUT = path.resolve(
  PROJECT_ROOT,
  "..",
  "sectors_extensions",
  "packages",
  "core",
  "src",
  "schema.ts",
);
const OUTPUT = path.resolve(
  PROJECT_ROOT,
  "packages",
  "core",
  "src",
  "schema.ts",
);

// ── Helpers ──────────────────────────────────────────────────

function serializeValue(val: unknown, indent = 2): string {
  if (val === undefined) return "";
  if (typeof val === "string") return JSON.stringify(val);
  if (typeof val === "number" || typeof val === "boolean") return String(val);
  if (Array.isArray(val)) {
    if (val.length === 0) return "[]";
    const items = val.map((v) => serializeValue(v, indent + 2));
    const inner = items.map((v) => `${" ".repeat(indent + 2)}${v}`);
    return `[\n${inner.join(",\n")}\n${" ".repeat(indent)}]`;
  }
  if (typeof val === "object" && val !== null) {
    const obj = val as Record<string, unknown>;
    const keys = Object.keys(obj);
    if (keys.length === 0) return "{}";
    const entries = keys.map((k) => {
      const v = serializeValue(obj[k], indent + 2);
      const key = k.includes("-") ? JSON.stringify(k) : k;
      return `${" ".repeat(indent + 2)}${key}: ${v}`;
    });
    return `{\n${entries.join(",\n")}\n${" ".repeat(indent)}}`;
  }
  return String(val);
}

// ── Main ─────────────────────────────────────────────────────

async function main() {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const schemaUrl = pathToFileURL(INPUT).href;
  const mod = (await import(schemaUrl)) as {
    API_SCHEMA: Array<Record<string, unknown>>;
  };
  const apiSchema = mod.API_SCHEMA;

  // ── Determine real constant names from the source module ──
  // Source exports are like SECTORS_SCREEN_DEF, SECTORS_COMPANY_OVERVIEW_DEF
  const constNames: string[] = [];
  for (const key in mod) {
    if (key.endsWith("_DEF") && key !== "EndpointDef") {
      constNames.push(key);
    }
  }

  const lines: string[] = [
    "// ============================================================",
    // schema.ts — AUTO-GENERATED by scripts/generate_schema.ts
    "// DO NOT EDIT MANUALLY.",
    "// Regenerate with: npx tsx scripts/generate_schema.ts",
    "// ============================================================",
    "",
  ];

  // ── Type definitions ───────────────────────────────────────
  lines.push("export interface ParamDef {");
  lines.push("  name: string;");
  lines.push('  type: "string" | "number" | "boolean";');
  lines.push("  description: string;");
  lines.push("  optional?: boolean;");
  lines.push("  example?: string;");
  lines.push("}");
  lines.push("");
  lines.push("export interface EndpointDef {");
  lines.push("  functionName: string;");
  lines.push("  path: string;");
  lines.push("  description: string;");
  lines.push("  params: ParamDef[];");
  lines.push("  extraQueryParams?: Record<string, unknown>;");
  lines.push("  exchange?: string;");
  lines.push("  category?: string;");
  lines.push('  "x-mdx-path"?: string;');
  lines.push("}");
  lines.push("");

  // ── Endpoint definitions ───────────────────────────────────
  const generatedConstNames: string[] = [];

  for (const def of apiSchema) {
    const name = def.functionName as string;
    const constName = `${name}_DEF`;
    generatedConstNames.push(constName);

    lines.push(`export const ${constName}: EndpointDef = {`);
    lines.push(`  functionName: ${JSON.stringify(name)},`);
    lines.push(`  path: ${JSON.stringify(def.path)},`);
    lines.push(`  description: ${JSON.stringify(def.description)},`);
    if (def.exchange) {
      lines.push(`  exchange: ${JSON.stringify(def.exchange)},`);
    }
    if (def.category) {
      lines.push(`  category: ${JSON.stringify(def.category)},`);
    }
    if (def["x-mdx-path"]) {
      lines.push(`  "x-mdx-path": ${JSON.stringify(def["x-mdx-path"])},`);
    }

    // Params
    const params = def.params as Array<Record<string, unknown>> | undefined;
    if (params && params.length > 0) {
      lines.push(`  params: [`);
      for (const p of params) {
        const pFields: string[] = [];
        pFields.push(`name: ${JSON.stringify(p.name)}`);
        pFields.push(`type: ${JSON.stringify(p.type)}`);
        pFields.push(`description: ${JSON.stringify(p.description)}`);
        if (p.optional) pFields.push(`optional: true`);
        if (p.example !== undefined) {
          pFields.push(`example: ${JSON.stringify(p.example)}`);
        }
        lines.push(`    { ${pFields.join(", ")} },`);
      }
      lines.push(`  ],`);
    } else {
      lines.push(`  params: [],`);
    }

    // Extra query params
    if (def.extraQueryParams) {
      const eqp = serializeValue(def.extraQueryParams, 4);
      lines.push(`  extraQueryParams: ${eqp},`);
    }

    lines.push("};");
    lines.push("");
  }

  // ── API_SCHEMA array ───────────────────────────────────────
  lines.push("export const API_SCHEMA: EndpointDef[] = [");
  for (const cn of generatedConstNames) {
    lines.push(`  ${cn},`);
  }
  lines.push("];");
  lines.push("");

  const content = lines.join("\n");
  fs.writeFileSync(OUTPUT, content, "utf-8");
  console.log(`✓ Generated: ${OUTPUT}`);
  console.log(`  ${generatedConstNames.length} endpoint(s)`);
}

main().catch((err) => {
  console.error("Fatal error:", err);
  process.exit(1);
});
